"""Export a project as a runnable PicoGK (LEAP 71) C# program.

PicoGK is the open-source voxel geometry kernel that LEAP 71's Noyron model is
built on. The generated program rebuilds every part in PicoGK: lattice and
gyroid parts from the same implicit fields as computational.py, and standard
parts by voxelising their STL. Results open in the PicoGK viewer and are saved
as STL files.

PicoGK's native runtime ships for Windows x64 and Apple-silicon macOS, so run
the program on one of those:   cd out/picogk && dotnet run
"""
from __future__ import annotations

from pathlib import Path

from .computational import COMPUTATIONAL_DEFAULTS, resolved_params as comp_params
from .spec import Project

PICOGK_VERSION = "2.3.0"

CSPROJ = f"""<Project Sdk="Microsoft.NET.Sdk">
  <PropertyGroup>
    <OutputType>Exe</OutputType>
    <TargetFramework>net9.0</TargetFramework>
    <ImplicitUsings>enable</ImplicitUsings>
    <Nullable>enable</Nullable>
  </PropertyGroup>
  <ItemGroup>
    <PackageReference Include="PicoGK" Version="{PICOGK_VERSION}" />
  </ItemGroup>
</Project>
"""

IMPLICITS = r"""
// ---- Implicit fields: signed distance, negative inside the material (mm) ----
static class Sdf
{
    public static float Box(in Vector3 p, float w, float l, float h)
    {
        Vector3 q = new(MathF.Abs(p.X - w / 2) - w / 2,
                        MathF.Abs(p.Y - l / 2) - l / 2,
                        MathF.Abs(p.Z - h / 2) - h / 2);
        float outside = Vector3.Max(q, Vector3.Zero).Length();
        float inside  = MathF.Min(MathF.Max(q.X, MathF.Max(q.Y, q.Z)), 0f);
        return outside + inside;
    }

    public static float Gyroid(in Vector3 p, float cell, float wall)
    {
        float k = 2f * MathF.PI / cell;
        float g = MathF.Sin(k * p.X) * MathF.Cos(k * p.Y)
                + MathF.Sin(k * p.Y) * MathF.Cos(k * p.Z)
                + MathF.Sin(k * p.Z) * MathF.Cos(k * p.X);
        return MathF.Abs(g) / (k * 1.25f) - wall / 2f;
    }

    static float Mod(float a, float m) => ((a % m) + m) % m;

    static readonly Vector3[] Diagonals =
    {
        Vector3.Normalize(new( 1,  1,  1)), Vector3.Normalize(new( 1,  1, -1)),
        Vector3.Normalize(new( 1, -1,  1)), Vector3.Normalize(new(-1,  1,  1)),
    };

    public static float Bcc(in Vector3 p, float cell, float radius)
    {
        Vector3 c = new(Mod(p.X, cell) - cell / 2, Mod(p.Y, cell) - cell / 2, Mod(p.Z, cell) - cell / 2);
        float best = float.MaxValue;
        foreach (Vector3 d in Diagonals)
            best = MathF.Min(best, (c - Vector3.Dot(c, d) * d).Length());
        return best - radius;
    }
}

class GyroidBlock(float w, float l, float h, float cell, float wall, float skin) : IImplicit
{
    public BBox3 Bounds => new(new Vector3(-1), new Vector3(w + 1, l + 1, h + 1));
    public float fSignedDistance(in Vector3 p)
    {
        float box    = Sdf.Box(p, w, l, h);
        float plates = MathF.Max(box, MathF.Min(p.Z - skin, (h - skin) - p.Z));
        float core   = MathF.Max(box, Sdf.Gyroid(p, cell, wall));
        return MathF.Min(plates, core);
    }
}

class LatticeBlock(float w, float l, float h, float cell, float strut, float skin) : IImplicit
{
    public BBox3 Bounds => new(new Vector3(-1), new Vector3(w + 1, l + 1, h + 1));
    public float fSignedDistance(in Vector3 p)
    {
        float box    = Sdf.Box(p, w, l, h);
        float plates = MathF.Max(box, MathF.Min(p.Z - skin, (h - skin) - p.Z));
        float struts = MathF.Max(box, Sdf.Bcc(p, cell, strut / 2f));
        return MathF.Min(plates, struts);
    }
}
"""


def _f(v: float) -> str:
    return f"{v:g}f"


def program_cs(project: Project) -> str:
    feats = [min(comp_params(p).get("wall", 1e9), comp_params(p).get("strut_diameter", 1e9),
                 comp_params(p)["skin"])
             for p in project.parts if p.type in COMPUTATIONAL_DEFAULTS]
    voxel = max(0.1, round(min(feats) / 4, 2)) if feats else 0.5

    calls = []
    for i, part in enumerate(project.parts):
        label = part.name.replace('"', "'")
        if part.type in COMPUTATIONAL_DEFAULTS:
            p = comp_params(part)
            if part.type == "gyroid_block":
                ctor = (f"new GyroidBlock({_f(p['width'])}, {_f(p['length'])}, {_f(p['height'])}, "
                        f"{_f(p['cell_size'])}, {_f(p['wall'])}, {_f(p['skin'])})")
            else:
                ctor = (f"new LatticeBlock({_f(p['width'])}, {_f(p['length'])}, {_f(p['height'])}, "
                        f"{_f(p['cell_size'])}, {_f(p['strut_diameter'])}, {_f(p['skin'])})")
            calls.append(f'        BuildImplicit("{part.id}", "{label}", {ctor}, {i});')
        else:
            calls.append(f'        BuildFromStl("{part.id}", "{label}", {i});')

    return f"""// {project.name}
// Generated by engineering_ai. Requires .NET 9 and runs on Windows x64 or Apple-silicon macOS.
//   dotnet run
// Parts open in the PicoGK viewer and are written to ./output as STL.

using System.Numerics;
using PicoGK;

static class Program
{{
    static readonly string PartsDir  = Path.GetFullPath(Path.Combine(Directory.GetCurrentDirectory(), "..", "parts"));
    static readonly string OutputDir = Path.Combine(Directory.GetCurrentDirectory(), "output");
    const float Spacing = 20f; // gap between parts in the viewer (mm)
    static float _x = 0f;

    static void Main()
    {{
        try
        {{
            Library.Go({_f(voxel)}, Run);
        }}
        catch (Exception e)
        {{
            Console.WriteLine("PicoGK failed: " + e.Message);
        }}
    }}

    static void Run()
    {{
        Directory.CreateDirectory(OutputDir);
{chr(10).join(calls)}
        Library.Log("Done. STL files are in " + OutputDir);
    }}

    static void Show(Voxels vox, int group)
    {{
        Library.oViewer().Add(vox, group);
    }}

    static void BuildImplicit(string id, string name, IImplicit field, int group)
    {{
        BBox3 bounds = field switch
        {{
            GyroidBlock g  => g.Bounds,
            LatticeBlock l => l.Bounds,
            _ => throw new ArgumentException("unknown implicit")
        }};
        Library.Log($"Building {{id}} {{name}} (implicit)");
        Voxels vox = new(field, bounds);
        Save(id, vox);
        Show(vox, group);
    }}

    static void BuildFromStl(string id, string name, int group)
    {{
        string path = Path.Combine(PartsDir, id + ".stl");
        if (!File.Exists(path)) {{ Library.Log($"Skipping {{id}}: {{path}} not found"); return; }}
        Library.Log($"Voxelising {{id}} {{name}} from STL");
        Mesh msh = Mesh.mshFromStlFile(path);
        Voxels vox = new(msh);
        Save(id, vox);
        Show(vox, group);
    }}

    static void Save(string id, Voxels vox)
    {{
        using Mesh msh = new(vox);
        msh.SaveToStlFile(Path.Combine(OutputDir, id + "_picogk.stl"));
    }}
}}
{IMPLICITS}"""


def export_project(project: Project, out_dir: Path) -> list[str]:
    out_dir.mkdir(parents=True, exist_ok=True)
    (out_dir / "EngineeringAI.PicoGK.csproj").write_text(CSPROJ)
    (out_dir / "Program.cs").write_text(program_cs(project))
    (out_dir / "README.txt").write_text(
        "PicoGK project generated by engineering_ai\n\n"
        "1. Install the .NET 9 SDK (https://dotnet.microsoft.com/download).\n"
        "2. On Windows x64 or an Apple-silicon Mac, open a terminal in this folder.\n"
        "3. Run:  dotnet run\n\n"
        "The PicoGK viewer opens with every part; STL files are saved in ./output.\n"
        "Keep this folder next to the 'parts' folder so standard parts can be loaded.\n")
    return ["EngineeringAI.PicoGK.csproj", "Program.cs", "README.txt"]
