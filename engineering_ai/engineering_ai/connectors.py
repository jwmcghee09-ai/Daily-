"""Import scripts that load a generated project straight into desktop CAD.

  out/connectors/fusion360/EngineeringAIImport/   Fusion 360 script (STEP parts)
  out/connectors/freecad/ImportProject.FCMacro    FreeCAD macro (STEP + STL parts)
  out/connectors/solidworks/ImportParts.swb       SolidWorks macro (STEP -> SLDPRT)

Each script finds the parts in ../../parts relative to itself, so the out/
folder can be zipped and moved to another computer. Onshape is handled by the
REST API in onshape.py instead.
"""
from __future__ import annotations

from pathlib import Path

from .spec import Project


def _size(files: list[str], part) -> float:
    vals = [v for k, v in part.params.items()
            if k in ("width", "length", "height", "outer_diameter", "leg_a", "leg_b")]
    return max(vals or [100.0])


def _pick(files: list[str], exts: tuple[str, ...]) -> str | None:
    for ext in exts:
        for f in files:
            if f.endswith(ext):
                return f
    return None


FUSION_PY = '''"""Fusion 360 script generated by engineering_ai: imports the project's STEP parts.
Install: Utilities > Add-Ins > Scripts and Add-Ins > + (My Scripts) > pick this folder > Run.
"""
import os
import traceback

import adsk.core
import adsk.fusion

PROJECT = {project!r}
PARTS = {parts!r}  # (file, name, x offset in mm)


def run(context):
    ui = None
    try:
        app = adsk.core.Application.get()
        ui = app.userInterface
        here = os.path.dirname(os.path.abspath(__file__))
        parts_dir = os.path.normpath(os.path.join(here, "..", "..", "..", "parts"))

        app.documents.add(adsk.core.DocumentTypes.FusionDesignDocumentType)
        design = adsk.fusion.Design.cast(app.activeProduct)
        root = design.rootComponent
        im = app.importManager

        done, missing = 0, []
        for fname, name, x_mm in PARTS:
            path = os.path.join(parts_dir, fname)
            if not os.path.exists(path):
                missing.append(fname)
                continue
            before = root.occurrences.count
            im.importToTarget(im.createSTEPImportOptions(path), root)
            if root.occurrences.count > before:      # spread parts out along X
                occ = root.occurrences.item(root.occurrences.count - 1)
                m = adsk.core.Matrix3D.create()
                m.translation = adsk.core.Vector3D.create(x_mm / 10.0, 0, 0)  # API units are cm
                occ.transform = m
                occ.component.name = name
            done += 1

        msg = "Imported {{}} part(s) for {{}}.".format(done, PROJECT)
        if missing:
            msg += "\\nNot found: " + ", ".join(missing)
        ui.messageBox(msg)
    except Exception:
        if ui:
            ui.messageBox("Import failed:\\n" + traceback.format_exc())
'''

FUSION_MANIFEST = '''{{
  "autodeskProduct": "Fusion360",
  "type": "script",
  "author": "engineering_ai",
  "description": {{"": "Import {project} parts"}},
  "supportedOS": "windows|mac",
  "editEnabled": true
}}
'''

FREECAD_MACRO = '''# FreeCAD macro generated by engineering_ai: imports every part of the project.
# Run: Macro > Macros... > choose this file > Execute   (or: freecadcmd ImportProject.FCMacro)
import os

import FreeCAD
import Import
import Mesh

PROJECT = {project!r}
PARTS = {parts!r}  # (file, name, x offset in mm)

try:
    HERE = os.path.dirname(os.path.abspath(__file__))
except NameError:  # some FreeCAD versions run macros without __file__
    HERE = {here!r}
PARTS_DIR = os.path.normpath(os.path.join(HERE, "..", "..", "parts"))

doc = FreeCAD.newDocument("EngineeringAI")
for fname, name, x_mm in PARTS:
    path = os.path.join(PARTS_DIR, fname)
    if not os.path.exists(path):
        FreeCAD.Console.PrintWarning("Not found: " + path + "\\n")
        continue
    before = set(o.Name for o in doc.Objects)
    if fname.lower().endswith((".step", ".stp")):
        Import.insert(path, doc.Name)
    else:
        Mesh.insert(path, doc.Name)
    for obj in doc.Objects:
        if obj.Name in before or obj.InList or not hasattr(obj, "Placement"):
            continue
        pl = obj.Placement
        pl.Base = pl.Base + FreeCAD.Vector(x_mm, 0, 0)
        obj.Placement = pl
        obj.Label = name
doc.recompute()
out = os.path.join(HERE, "EngineeringAI.FCStd")
doc.saveAs(out)
FreeCAD.Console.PrintMessage("Saved " + out + "\\n")
if FreeCAD.GuiUp:
    import FreeCADGui
    FreeCADGui.activeDocument().activeView().viewIsometric()
    FreeCADGui.SendMsgToActiveView("ViewFit")
'''

SOLIDWORKS_SWB = """' SolidWorks macro generated by engineering_ai: imports STEP parts and saves SLDPRT files.
' Run: Tools > Macro > Run... > choose this file.
Dim swApp As Object

Sub main()
    Set swApp = Application.SldWorks
    Dim folder As String
    folder = swApp.GetCurrentMacroPathFolder & "\\..\\..\\parts\\"
{calls}
    MsgBox "Finished importing {project}. SLDPRT files were saved in the parts folder."
End Sub

Sub ImportPart(folder As String, fileName As String)
    Dim importData As Object
    Dim errs As Long
    Dim model As Object
    Set importData = swApp.GetImportFileData(folder & fileName)
    Set model = swApp.LoadFile4(folder & fileName, "r", importData, errs)
    If model Is Nothing Then
        MsgBox "Could not import " & fileName & " (error " & errs & ")"
        Exit Sub
    End If
    model.SaveAs3 folder & Replace(fileName, ".step", ".SLDPRT"), 0, 2
End Sub
"""


def export_connectors(project: Project, cad_files: dict[str, list[str]], out_dir: Path) -> list[str]:
    """Write all import scripts under out_dir (normally out/connectors)."""
    step, mixed, x = [], [], 0.0
    for part in project.parts:
        files = cad_files.get(part.id, [])
        s = _pick(files, (".step",))
        m = _pick(files, (".step", ".stl"))
        if s:
            step.append((s, part.name, x))
        if m:
            mixed.append((m, part.name, x))
        x += _size(files, part) + 30

    written = []
    fdir = out_dir / "fusion360" / "EngineeringAIImport"
    fdir.mkdir(parents=True, exist_ok=True)
    (fdir / "EngineeringAIImport.py").write_text(FUSION_PY.format(project=project.name, parts=step))
    (fdir / "EngineeringAIImport.manifest").write_text(FUSION_MANIFEST.format(project=project.name))
    written += ["fusion360/EngineeringAIImport/EngineeringAIImport.py",
                "fusion360/EngineeringAIImport/EngineeringAIImport.manifest"]

    (out_dir / "freecad").mkdir(parents=True, exist_ok=True)
    (out_dir / "freecad" / "ImportProject.FCMacro").write_text(
        FREECAD_MACRO.format(project=project.name, parts=mixed,
                             here=str((out_dir / "freecad").resolve())))
    written.append("freecad/ImportProject.FCMacro")

    (out_dir / "solidworks").mkdir(parents=True, exist_ok=True)
    calls = "\n".join(f'    ImportPart folder, "{f}"' for f, _, _ in step)
    (out_dir / "solidworks" / "ImportParts.swb").write_text(
        SOLIDWORKS_SWB.format(calls=calls, project=project.name.replace('"', "'")))
    written.append("solidworks/ImportParts.swb")
    return written
